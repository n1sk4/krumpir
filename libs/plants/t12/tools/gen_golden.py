#!/usr/bin/env python3
"""Independent reference for the T12 plant: writes libs/test/test_t12_plant/golden.h.

The thermal network is solved in closed form with an eigendecomposition (the C code uses a
truncated matrix exponential), and the sense node is integrated with RK4 at 50 us on the exact
temperatures. The parameters repeat T12_PARAMS_DEFAULT on purpose: if one side changes, the golden
test fails. Needs numpy only.

Scenario: 10 Hz heating cycles at 1 ms steps (90 ms on, 10 ms off) for 20 s from ambient. At
10 s the tip touches a joint (extra 0.3 W/K). Rows are taken at the end of steps 89, 92, 95 and 99
of every tenth cycle: heater just switched off, settling, and the readable end of the off window.

    python3 -I libs/plants/t12/tools/gen_golden.py [OUT.h]   (default: the test's golden.h)

Exit status: 0 ok, 2 usage.
"""
import argparse
import pathlib
import sys

import numpy as np

AMB, DT, SUB = 25.0, 1e-3, 20  # ambient, step, RK4 substeps per step
C_H, C_T, C_C = 0.25, 0.8, 15.0
R_HT, R_TA, R_TC, R_CA = 0.5, 35.0, 150.0, 15.0
V_SUP, R_COIL = 24.0, 8.0
SEEBECK, GAIN, OFFSET, V_CLAMP, TAU = 21e-6, 250.0, 10e-6, 3.3, 0.5e-3
CYCLE, ON_STEPS, CYCLES = 100, 90, 200
LOAD_STEP, LOAD_G = 10000, 0.3
SAMPLE_OFFSETS = (89, 92, 95, 99)


def system(g_load):
    g = 1 / R_TA + g_load
    a = np.array([
        [-1 / (R_HT * C_H), 1 / (R_HT * C_H), 0],
        [1 / (R_HT * C_T), -(1 / R_HT + g + 1 / R_TC) / C_T, 1 / (R_TC * C_T)],
        [0, 1 / (R_TC * C_C), -(1 / R_TC + 1 / R_CA) / C_C],
    ])
    b = np.array([[1 / C_H, 0], [0, g / C_T], [0, 1 / (R_CA * C_C)]])
    lam, v = np.linalg.eig(a)
    return a, b, lam.real, v.real, np.linalg.inv(v.real)


def target(x):
    return min(max(GAIN * (SEEBECK * (x[0] - x[2]) + OFFSET), 0.0), V_CLAMP)


def main(out):
    x = np.full(3, AMB)
    v_amp = min(max(GAIN * OFFSET, 0.0), V_CLAMP)
    sys_ = system(0.0)
    rows = []
    for k in range(CYCLES * CYCLE):
        if k == LOAD_STEP:
            sys_ = system(LOAD_G)
        a, b, lam, ev, evi = sys_
        on = k % CYCLE < ON_STEPS
        u = np.array([V_SUP**2 / R_COIL if on else 0.0, AMB])
        x_ss = -np.linalg.solve(a, b @ u)

        def at(t):
            return ev @ (np.exp(lam * t) * (evi @ (x - x_ss))) + x_ss

        if on:
            v_amp = V_CLAMP
        else:
            h = DT / SUB
            for i in range(SUB):  # RK4 on dv/dt = (target(T(t)) - v) / TAU
                t0 = i * h
                f = lambda t, v: (target(at(t)) - v) / TAU
                k1 = f(t0, v_amp)
                k2 = f(t0 + h / 2, v_amp + h / 2 * k1)
                k3 = f(t0 + h / 2, v_amp + h / 2 * k2)
                k4 = f(t0 + h, v_amp + h * k3)
                v_amp += h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        x = at(DT)
        cycle, pos = divmod(k, CYCLE)
        if cycle % 10 == 0 and pos in SAMPLE_OFFSETS:
            rows.append((k + 1, *x, v_amp))

    lines = [
        "/* Generated by plants/t12/tools/gen_golden.py from an independent numpy reference. */",
        "#ifndef GOLDEN_H",
        "#define GOLDEN_H",
        "",
        f"#define GOLDEN_LOAD_STEP {LOAD_STEP}",
        f"#define GOLDEN_LOAD_G {LOAD_G}",
        "",
        "typedef struct {",
        "  int step; /* steps completed */",
        "  double t_h, t_t, t_c, v_amp;",
        "} golden_t;",
        "",
        "static const golden_t GOLDEN[] = {",
    ]
    lines += [f"    {{{s}, {h:.12g}, {t:.12g}, {c:.12g}, {v:.12g}}}," for s, h, t, c, v in rows]
    lines += ["};", "", f"#define GOLDEN_N {len(rows)}", "", "#endif", ""]
    pathlib.Path(out).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(rows)} rows")


if __name__ == "__main__":
    default = pathlib.Path(__file__).resolve().parents[3] / "test" / "test_t12_plant" / "golden.h"
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out", nargs="?", default=default, help="the header to write")
    sys.exit(main(ap.parse_args().out))
